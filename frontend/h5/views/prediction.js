import { api } from "../api.js";
import { state } from "../state.js";
import { formatBeijingTime } from "../components/time.js";
import { errorState, loading, sectionTitle } from "../components/layout.js";
import { probabilityGrid, confidenceBadge } from "../components/probability.js";
import { scorelineList } from "../components/scorelines.js";
import { vipGate } from "../components/vipGate.js";

function metaLine(data, meta) {
  return `
    <div class="kickoff">
      ${data.model_version || ""} · ${formatBeijingTime(data.data_updated_at || data.generated_at, "Update time unavailable")} · ${meta?.source || ""}
    </div>
  `;
}

function vipSection(data) {
  return `
    <section class="card">
      <h2>VIP data</h2>
      <div class="prob-grid">
        <div class="prob-box"><div class="prob-label">Over 2.5 goals</div><div class="prob-value">${((data.over25 || 0) * 100).toFixed(1)}%</div></div>
        <div class="prob-box"><div class="prob-label">Both teams to score</div><div class="prob-value">${((data.btts || 0) * 100).toFixed(1)}%</div></div>
        <div class="prob-box"><div class="prob-label">Market edge</div><div class="prob-value">${data.market_edge ? "Yes" : "-"}</div></div>
      </div>
      <h3>Top 15 scorelines</h3>
      ${scorelineList(data.top_scorelines || [], 15)}
    </section>
  `;
}

function aiSection(analysisText) {
  return `
    <section class="card">
      <h2>AI analysis</h2>
      <p>${analysisText}</p>
    </section>
  `;
}

export async function renderPrediction(root, fixtureId) {
  root.innerHTML = loading("Loading forecast...");
  try {
    const basic = await api.prediction(fixtureId, state.userId, state.sessionToken);
    let vip = null;
    let analysis = null;
    try {
      vip = await api.vipPrediction(fixtureId, state.userId, state.sessionToken);
      const analysisResult = await api.analysis(fixtureId, state.userId, state.sessionToken);
      analysis = analysisResult.data?.analysis || null;
    } catch (_) {
      vip = null;
      analysis = null;
    }

    const data = vip?.data || basic.data;
    root.innerHTML = `
      ${sectionTitle(`${data.home_team} vs ${data.away_team}`)}
      <section class="card">
        ${confidenceBadge(data.confidence || 0)}
        ${metaLine(data, basic.meta)}
        ${probabilityGrid(data.probabilities || {})}
      </section>
      <section class="card">
        <h2>Most likely scores</h2>
        ${scorelineList(data.top_scorelines || [], 3)}
      </section>
      ${vip ? vipSection(data) : vipGate("Unlock the full forecast with a VIP code")}
      ${vip ? aiSection(analysis || "AI analysis is temporarily unavailable.") : vipGate("AI analysis", "Checked on VIP Cartoon to see English analysis generated by the model in conjunction with pre-game information.")}
    `;
    root.querySelectorAll("[data-route]").forEach((button) => {
      button.addEventListener("click", () => {
        window.location.hash = button.dataset.route;
      });
    });
  } catch (error) {
    root.innerHTML = errorState(error);
  }
}
